// Scope the world's four GLOBAL rules to its host.
//
// The world's stylesheet assumes it owns the page: :root custom properties,
// a `*` box-sizing reset, `html, body` background/colour/font, and a bare `a`.
// Loaded into the Buildanta site those four repaint the site's own typography
// and background — the other 104 rules are already .world-* prefixed and are
// left exactly as they are.
//
// Generated rather than hand-edited so the world's stylesheet stays the single
// source: re-run this after any change there.
//
//   node tools/scope-world-css.cjs
const fs = require('fs')
const path = require('path')
const SRC = path.join(__dirname, '..', 'src', 'world', 'style.css')
const OUT = path.join(__dirname, '..', 'src', 'world', 'style.scoped.css')
const HOST = '.world-host'

let css = fs.readFileSync(SRC, 'utf8')

// :root -> the host, so the world's tokens exist only inside it.
css = css.replace(/^:root\s*\{/m, `${HOST} {`)
// The reset applies within the host only.
css = css.replace(/^\* \{ box-sizing: border-box; \}/m, `${HOST} *, ${HOST} *::before, ${HOST} *::after { box-sizing: border-box; }`)
// html, body -> the host itself. It is fixed and full-bleed, so it plays the
// same role the page did.
css = css.replace(/^html, body \{/m, `${HOST} {`)
// A bare `a` would restyle every link on the site.
css = css.replace(/^a \{ color: inherit; text-decoration: none; \}/m, `${HOST} a { color: inherit; text-decoration: none; }`)

const header = `/* GENERATED by tools/scope-world-css.cjs — do not edit.
   Source: src/world/style.css. Four global rules scoped to ${HOST}; everything
   else is already .world-* prefixed and untouched. */\n\n`
fs.writeFileSync(OUT, header + css)

const leftovers = css.split('\n').filter((l) => /^(html, body|:root|\* \{|a \{)/.test(l))
console.log(`wrote ${path.relative(process.cwd(), OUT)}`)
console.log(leftovers.length ? `WARNING unscoped globals remain: ${leftovers.join(' | ')}`
                             : 'no unscoped global rules remain')
